"""Generate the single roadmap and check repository-owned references."""

import argparse
import csv
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
LEDGER = ROOT / 'docs/milestones.tsv'
ROADMAP = ROOT / 'docs/roadmap.md'


def dependency_ids(value):
    return re.findall(r'\b(?:DL|SA|RC)\d+\b', value)


def check_dependencies(rows, final):
    graph = {r['id']: dependency_ids(r['depends_on']) +
             (dependency_ids(r['final_profile_requires']) if final else []) for r in rows}
    seen, active = set(), set()

    def visit(name):
        assert name in graph, f'Unknown dependency {name}'
        assert name not in active, f'Dependency cycle at {name}'
        if name in seen:
            return
        active.add(name)
        for parent in graph[name]:
            visit(parent)
        active.remove(name)
        seen.add(name)

    for name in graph:
        visit(name)


