def check_links():
    files = [ROOT/'README.md', ROOT/'CONTRIBUTING.md', ROOT/'AGENTS.md']
    files += list((ROOT/'docs').rglob('*.md'))
    files += [ROOT/'examples/rolling_contact_arm/README.md']
    files += list((ROOT/'reports').rglob('README.md'))
    count = 0
    for path in files:
        relative = path.relative_to(ROOT)
        if relative.is_relative_to('docs/archive') and relative != Path('docs/archive/README.md'):
            continue
        if relative.is_relative_to('reports/research') and relative != Path('reports/research/README.md'):
            continue
        for target in re.findall(r'\]\((<[^>]+>|[^)]+)\)', path.read_text()):
            target = target.strip('<>')
            if '://' in target or target.startswith('#'):
                continue
            resolved = (path.parent/target.split('#')[0]).resolve()
            assert resolved.is_relative_to(ROOT), f'Link escapes repository: {path}: {target}'
            rel = resolved.relative_to(ROOT)
            assert not any(p.startswith(('.worktrees', '.local', '.venv')) or p == 'results' for p in rel.parts), f'Link needs unpublished data: {path}: {target}'
            assert resolved.exists(), f'Broken link: {path}: {target}'
            count += 1
    return count


def check():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write-roadmap', action='store_true')
    args = parser.parse_args()
    with LEDGER.open() as file:
        rows = list(csv.DictReader(file, delimiter='\t'))
    ids = [row['id'] for row in rows]
    assert ids and len(ids) == len(set(ids)), 'Milestone IDs must be unique'
    assert all(re.fullmatch(r'(?:DL|SA|RC)\d{2}', mid) for mid in ids), 'Invalid milestone ID'
    assert {r['id']:r['final_profile_requires'] for r in rows if r['final_profile_requires']} == {'SA05':'RC03','SA07':'RC04'}
    check_dependencies(rows, False)
    check_dependencies(rows, True)
    for row in rows:
        for evidence in row['evidence'].split(';'):
            if evidence.strip():
                assert (ROOT/evidence.strip()).is_file(), f'Missing evidence: {evidence}'
    expected = render_roadmap(rows)
    if args.write_roadmap:
        ROADMAP.write_text(expected)
    assert ROADMAP.read_text() == expected, 'Regenerate roadmap with --write-roadmap'
    archive = ROOT/'docs/archive'
    manifest = json.loads((archive/'manifest.json').read_text())
    for name, digest in manifest.items():
        assert hashlib.sha256((archive/name).read_bytes()).hexdigest() == digest, f'Historical archive changed: {name}'
    legacy = set(re.findall(r'^\|\s*([A-Z]+\d+(?:\.\d+)?)\s*\|', (archive/'workbench-plan-2026-10-20.md').read_text(), re.M))
    with (archive/'legacy-milestone-map.tsv').open() as file:
        mapped = list(csv.DictReader(file, delimiter='\t'))
    assert len(mapped) == len(legacy) == 195 and {r['legacy_id'] for r in mapped} == legacy
    for report in ('verification.json','dream_contract.json'):
        result = json.loads((ROOT/'reports/rolling-contact'/report).read_text())
        for name, digest in result['sha256'].items():
            assert hashlib.sha256((ROOT/'examples/rolling_contact_arm'/name).read_bytes()).hexdigest() == digest, f'Sample evidence stale: {name}'
    print(f'PASS: {len(rows)} gates, both dependency graphs, 195 legacy mappings, archive hashes, sample hashes, {check_links()} portable links')


if __name__ == '__main__':
    check()
